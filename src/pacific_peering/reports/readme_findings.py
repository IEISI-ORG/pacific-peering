"""Refresh the counts in README.md's "Findings so far" section (owner, 2026-10-15).

The weekly discovery refresh runs this so the README's numbers don't drift
behind findings.db. Only the text between the two marker comments is
generated; the worked examples around it stay hand-written. Quarantined and
held findings are left out, the same rule the public report uses, so the
README and the site agree.

The block carries an "as of" date, but a week whose counts didn't change
leaves README.md untouched, so the refresh doesn't commit a date bump alone.

`uv run pacific-peering-readme-findings [--readme README.md]`
"""

from __future__ import annotations

import argparse
import json
import logging
import sqlite3
from collections import Counter
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from pacific_peering.analysis import store

logger = logging.getLogger(__name__)

README = Path("README.md")
IXP_REGISTRY = Path("data/analysis/ixp_lan_registry.json")
START = "<!-- findings-summary:start (generated by pacific-peering-readme-findings; edits here are overwritten) -->"
END = "<!-- findings-summary:end -->"
TOP_EXCHANGES = 4
_AS_OF_PREFIX = "_Counts as of "

_KIND_ROWS = (
    (store.KIND_CONFIRMED_DETOUR, "Confirmed detour",
     "Traffic between two in-scope networks passes through an exchange or carrier outside the fishbowl"),
    (store.KIND_CONFIRMED_LOCAL_TRANSIT, "Confirmed local transit",
     "A transit relationship inside the fishbowl, confirmed by RIS and Atlas"),
    (store.KIND_CANDIDATE_PEERING, "Candidate peering",
     "An adjacency seen in traceroutes that RIS does not confirm; a lead, not a finding"),
)


@dataclass(frozen=True)
class FindingsSummary:
    total: int
    by_kind: dict[str, int]
    measurements: int
    hubs: tuple[tuple[str, int], ...]
    exchanges: tuple[tuple[str, int], ...]
    same_economy_detours: int
    ixp_total: int
    ixp_in: int
    ixp_out: int
    ixp_unconfirmed: int


def _ranked(counter: Counter) -> tuple[tuple[str, int], ...]:
    return tuple(sorted(counter.items(), key=lambda kv: (-kv[1], kv[0])))


def summarize(conn: sqlite3.Connection, registry: dict) -> FindingsSummary:
    """Tally the reportable (non-quarantined) findings and the IXP registry."""
    findings = [f for f in store.all_findings(conn) if not store.is_quarantined(f)]
    ids = {f.id for f in findings}
    measurements = {
        row[1] for row in conn.execute("SELECT finding_id, measurement_id FROM corroborations") if row[0] in ids
    }
    detours = [f for f in findings if f.kind == store.KIND_CONFIRMED_DETOUR]
    kinds = Counter(f.kind for f in findings)
    flags = [entry.get("in_fishbowl") for entry in registry.values()]
    return FindingsSummary(
        total=len(findings),
        by_kind={kind: kinds.get(kind, 0) for kind, _, _ in _KIND_ROWS},
        measurements=len(measurements),
        hubs=_ranked(Counter(f.detour_hub for f in detours if f.detour_hub)),
        exchanges=_ranked(Counter(f.detour_ix_name for f in detours if f.detour_ix_name))[:TOP_EXCHANGES],
        same_economy_detours=sum(1 for f in detours if f.source_cc == f.target_cc),
        ixp_total=len(flags),
        ixp_in=sum(1 for v in flags if v is True),
        ixp_out=sum(1 for v in flags if v is False),
        ixp_unconfirmed=sum(1 for v in flags if v is None),
    )


def render_block(s: FindingsSummary, as_of: str) -> str:
    """The generated markdown between the markers (markers excluded)."""
    lines = [
        f"{_AS_OF_PREFIX}{as_of}, refreshed weekly from `data/analysis/findings.db`. "
        "Quarantined and held findings are left out, as in the public report._",
        "",
        f"The database holds {s.total} findings, backed by {s.measurements} RIPE Atlas "
        "traceroute measurements.",
        "",
        "| Kind | Count | What it means |",
        "|---|---|---|",
        *(f"| {label} | {s.by_kind[kind]} | {meaning} |" for kind, label, meaning in _KIND_ROWS),
    ]
    # Tables, not prose: carrier names already carry parentheses
    # ("AS6939 (Hurricane Electric)"), so "name (n)" reads badly.
    if s.hubs:
        lines += ["", "| Detour hub | Detours |", "|---|---|", *(f"| {name} | {n} |" for name, n in s.hubs)]
    if s.exchanges:
        lines += ["", "| Exchange or carrier (most common) | Detours |", "|---|---|",
                  *(f"| {name} | {n} |" for name, n in s.exchanges)]
    n = s.same_economy_detours
    lines += [
        "",
        f"In {n} detour{'' if n == 1 else 's'}, both ends are in the same economy.",
        "",
        f"IXP registry: {s.ixp_total} exchanges, {s.ixp_in} in the fishbowl, {s.ixp_out} outside, "
        f"{s.ixp_unconfirmed} unconfirmed.",
    ]
    return "\n".join(lines)


def _without_date(block: str) -> str:
    return "\n".join(line for line in block.strip().splitlines() if not line.startswith(_AS_OF_PREFIX))


def update_readme(text: str, s: FindingsSummary, as_of: str) -> str:
    """Return `text` with the marked block regenerated; unchanged if only the date would move."""
    head, sep, rest = text.partition(START)
    current, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise ValueError(f"README has no findings-summary markers ({START!r} ... {END!r})")
    block = render_block(s, as_of)
    if _without_date(current) == _without_date(block):
        return text
    return f"{head}{START}\n{block}\n{END}{tail}"


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--readme", type=Path, default=README)
    parser.add_argument("--registry", type=Path, default=IXP_REGISTRY)
    parser.add_argument("--db", type=Path, default=store.DEFAULT_DB_PATH)
    args = parser.parse_args()

    # store.connect() creates a missing database, and an empty one would
    # publish "0 findings" from an unattended cron job; refuse both instead.
    if not args.db.exists():
        raise SystemExit(f"no findings database at {args.db}; README left unchanged")
    conn = store.connect(args.db)
    try:
        summary = summarize(conn, json.loads(args.registry.read_text()))
    finally:
        conn.close()
    if summary.total == 0:
        raise SystemExit(f"{args.db} has 0 reportable findings; README left unchanged")
    old = args.readme.read_text()
    new = update_readme(old, summary, as_of=date.today().isoformat())
    if new == old:
        logger.info("README findings summary unchanged (%d findings)", summary.total)
        return
    args.readme.write_text(new)
    logger.info("README findings summary updated: %d findings, %d measurements", summary.total, summary.measurements)


if __name__ == "__main__":
    main()
